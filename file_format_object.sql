CREATE OR REPLACE TABLE OUR_FIRST_DB.PUBLIC.ORDERS_EX (
    ORDER_ID VARCHAR(30),
    AMOUNT INT,
    PROFIT INT,
    QUANTITY INT,
    CATEGORY VARCHAR(30),
    SUBCATEGORY VARCHAR(30)
);


CREATE OR REPLACE SCHEMA MANAGED_DB.file_formats;

// creating a file format object
CREATE OR REPLACE file format MANAGED_DB.FILE_FORMATS.MY_FILE_FORMAT;

DESC file format MANAGED_DB.FILE_FORMATS.MY_FILE_FORMAT;


// file format object
COPY INTO OUR_FIRST_DB.PUBLIC.ORDERS_EX 
    FROM @MANAGED_DB.EXTERNAL_STAGE.AWS_STAGE_ERROREX
    file_format = (FORMAT_NAME = MANAGED_DB.FILE_FORMATS.MY_FILE_FORMAT)
    files = ('OrderDetails_error.csv')
    ON_ERROR = 'SKIP_FILE_3';


ALTER FILE FORMAT MANAGED_DB.file_formats.my_file_format
    SET SKIP_HEADER = 1;


CREATE OR REPLACE FILE FORMAT MANAGED_DB.FILE_FORMATS.MY_FILE_FORMAT
    TYPE = JSON,
    TIME_FORMAT = AUTO;

DESC FILE FORMAT MANAGED_DB.file_formats.my_file_format;


// override properties
COPY INTO OUR_FIRST_DB.PUBLIC.ORDERS_EX 
    FROM @MANAGED_DB.EXTERNAL_STAGE.AWS_STAGE_ERROREX
    file_format = (FORMAT_NAME = MANAGED_DB.FILE_FORMATS.MY_FILE_FORMAT field_delimiter = ',' skip_header = 1)
    files = ('OrderDetails_error.csv')
    ON_ERROR = 'SKIP_FILE_3';